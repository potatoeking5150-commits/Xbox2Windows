"""Compare native and translated FIADD, FISUB, FISUBR, FIMUL, FIDIV and FIDIVR of the x87 leaf-function
profile, with an m16 or m32 integer operand.

Usage:
    python tests/cpu/x87_iarith.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_iarith.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_iarith.py check <harness> <native> <lifted> [controls...]

The exports, harness and guards follow tests/cpu/x87_add.py, and the other steps use the format of
tests/cpu/x87_moves.py. emit checks that every decoded x87 instruction is the form its sequence names.
The model converts the integer exactly, as tests/cpu/x87_integers.py does for FILD, and applies the
Fraction models of tests/cpu/x87_add.py, x87_sub.py, x87_mul.py and x87_div.py; it is independent of
tools/x87_soft.h.
"""
from pathlib import Path
import platform
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import x87_add as base  # noqa: E402  (tests/cpu is the script directory)
import x87_div as div  # noqa: E402
import x87_integers as integers  # noqa: E402
import x87_mul as mul  # noqa: E402
import x87_sub as sub  # noqa: E402
from x87_add import J, from_binary, m80_bytes, to_binary  # noqa: E402

INPUT, OUTPUT = base.INPUT, base.OUTPUT
SIZE = integers.SIZE
PTR = integers.PTR
FUNCTIONS = {"fiadd": base.add, "fisub": sub.sub, "fisubr": lambda a, b: sub.sub(b, a), "fimul": mul.mul,
             "fidiv": div.div, "fidivr": lambda a, b: div.div(b, a)}

# (op, "i16" | "i32", offset) is the new step, with ST(0) as the destination; the others use the
# x87_moves format. The m80 value is at offset 0 of the input block and the integer at 16.
SEQUENCES = {
    **{f"{op}_{k}": (k, [("fld", "m80", 0), (op, k, 16), ("fstp", "m80", 0)]) for op in FUNCTIONS
       for k in ("i16", "i32")},
    # An m64 value, rounded again by the m64 store.
    "fimul_i32_m64": ("f64i32", [("fld", "m64", 0), ("fimul", "i32", 16), ("fstp", "m64", 0)]),
    # Two integer operations in a row: an m32 integer at 16 and an m16 integer at 20.
    "fiadd_fisub": ("i32i16", [("fld", "m80", 0), ("fiadd", "i32", 16), ("fisub", "i16", 20), ("fstp", "m80", 0)]),
    # The eighth register; the integer is the low half of the m64 value loaded last.
    "fidivr_depth8": ("m64x8", [("fld", "m64", 8 * k) for k in range(8)] + [("fidivr", "i32", 56)]
                      + [("fstp", "m64", 8 * k) for k in range(8)]),
}

CONTROLS = {
    # FISUB subtracts ST(0) from the integer, as FISUBR does.
    "subrev": (re.compile(r"= x87_sub\((.*)  // fisub "), r"= x87_subr(\1  // fisub "),
    # FIDIV divides the integer by ST(0), as FIDIVR does.
    "divrev": (re.compile(r"= x87_div\((.*)  // fidiv "), r"= x87_divr(\1  // fidiv "),
    # An m16 integer is zero-extended instead of sign-extended.
    "zext16": (re.compile(r"static_cast<int16_t>\((load(?:_always)?)<uint16_t>\(a\)\)"), r"static_cast<int64_t>(\1<uint16_t>(a))"),
    # An m32 integer is zero-extended instead of sign-extended.
    "zext32": (re.compile(r"static_cast<int32_t>\((load(?:_always)?)<uint32_t>\(a\)\)"), r"static_cast<int64_t>(\1<uint32_t>(a))"),
    # An m16 integer is read as 32 bits; the two bytes after each m16 operand are not a sign extension.
    "wide16": (re.compile(r"static_cast<int16_t>\((load(?:_always)?)<uint16_t>\(a\)\)"), r"static_cast<int32_t>(\1<uint32_t>(a))"),
    # The result keeps 64 significand bits, as if the precision control did not apply.
    "pc64": (re.compile(r"x87_arith\{53, 16383, 0x7ffe\}"), "x87_arith{64, 16383, 0x7ffe}"),
}


# ---- MASM generation and decoding ------------------------------------------------------------------

def asm_line(step):
    if step[0] in FUNCTIONS:
        return f"    {step[0]} {PTR[step[1]]} ptr [rcx+{step[2]}]"
    return integers.asm_line(step)


def expected_form(step):
    return (step[0], step[1]) if step[0] in FUNCTIONS else integers.expected_form(step)


def decoded_form(i):
    from iced_x86 import MemorySize as S, Mnemonic as M

    if i.mnemonic in (M.FIADD, M.FISUB, M.FISUBR, M.FIMUL, M.FIDIV, M.FIDIVR):
        name = next(n for n, v in vars(M).items() if v == i.mnemonic).lower()
        return name, {S.INT16: "i16", S.INT32: "i32"}[i.memory_size]
    return integers.decoded_form(i)


def write_asm(asm_path, def_path):
    lines = ["; coverage: source cpu_aot_x87_iarith",
             "; Generated by tests/cpu/x87_iarith.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for the integer-operand arithmetic of the x87 leaf-function",
             "; profile. Each export reads an input block at RCX, writes an output block at RDX and returns with",
             "; the x87 stack empty.", ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER, is_x87

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name, (_, steps) in SEQUENCES.items():
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            body = region(pe, *bounds)
            decoded = [decoded_form(i) for i in body if is_x87(i)]
            wanted = [expected_form(s) for s in steps]
            if decoded != wanted:
                raise AssertionError(f"{name} assembled as {decoded}, expected {wanted}")
            code = lower(body, ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------

def read_integer(data, kind, offset):
    bits = integers.BITS[kind]
    raw = int.from_bytes(data[offset:offset + bits // 8], "little")
    return raw - ((raw >> (bits - 1)) << bits)


def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)

    def read(kind, offset):
        return int.from_bytes(data[offset:offset + SIZE[kind]], "little")

    for op, *args in SEQUENCES[name][1]:
        if op in FUNCTIONS:
            slots[-1] = FUNCTIONS[op](slots[-1], integers.from_integer(read_integer(data, *args)))
        elif op == "fld":
            raw = read(*args)
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if args[0] == "m80" else from_binary(args[0], raw))
        else:  # ("fstp", kind, offset)
            kind, offset = args
            v = slots.pop()
            encoded = v[0] | v[1] << 64 if kind == "m80" else to_binary(kind, v)
            out[offset:offset + SIZE[kind]] = encoded.to_bytes(SIZE[kind], "little")
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def edge_integers(bits, rng):
    """Zero, small values of both signs, powers of two, the extremes of the width and random values."""
    top = 1 << (bits - 1)
    values = [0, 1, -1, 2, -2, 3, -3, 7, 10, -10, 255, 256, -256, 1000, top - 1, -top, -top + 1, top // 2]
    if bits == 32:
        values += [(1 << 24) + 1, -(1 << 24) - 1, (1 << 30) + 3, 0x12345679, -0x76543211]
    values += [rng.randrange(-top, top) for _ in range(8)]
    return values


def operands(rng):
    """ST(0) values: the 34 special encodings, values whose low significand bits sit at or beside a
    53-bit rounding tie, full 64-bit significands, values at the edges of the exponent range, denormals
    and random values."""
    values = list(base.special_m80())
    for low in (0, 1, 0x400, 0x401, 0x3FF, 0x7FF, 0x800, 0xC00, (1 << 32) | 1, (1 << 63) - 1):
        for se in (0x3FFF, 0xBFFF, 0x3FFF + 52, 0xBFFF + 52, 0x3FFF + 62, 0x3FFF + 30, 0x7FFE, 0x0001):
            values.append((J | low, se))
    for _ in range(40):
        values.append((J | rng.getrandbits(63), rng.randint(0x3FFF - 70, 0x3FFF + 70) | rng.choice((0, 0x8000))))
        values.append((J | rng.getrandbits(63), rng.randint(1, 0x7FFE) | rng.choice((0, 0x8000))))
        values.append((rng.getrandbits(rng.randint(1, 64)) or 1, rng.choice((0, 0x8000))))
    return values


def integer_bytes(kind, n, rng):
    """The integer, then filler that is never its sign extension, so a wider read changes the value."""
    width = integers.BITS[kind] // 8
    filler = rng.randrange(1, 0xFFFF)
    if filler == (0xFFFF if n < 0 else 0):
        filler ^= 0x5A5A
    return (n & ((1 << (8 * width)) - 1)).to_bytes(width, "little") + filler.to_bytes(2, "little")


def cases():
    rng = random.Random(103)
    st0 = operands(rng)
    ints = {k: edge_integers(integers.BITS[k], rng) for k in ("i16", "i32")}
    f64 = base.f64_bits()
    blocks = {}
    for k in ("i16", "i32"):
        rows = [(v, n) for v in st0[:34] for n in ints[k]]  # every special encoding with every edge integer
        rows += [(v, n) for v in st0[34::2] for n in ints[k][::3]]
        rows += [(rng.choice(st0), rng.choice(ints[k])) for _ in range(300)]
        blocks[k] = [m80_bytes(v) + integer_bytes(k, n, rng) for v, n in rows]
    blocks["f64i32"] = [bits.to_bytes(8, "little") + b"\0" * 8 + integer_bytes("i32", n, rng)
                        for bits in f64[::2] for n in ints["i32"][::2]]
    blocks["i32i16"] = [m80_bytes(rng.choice(st0)) + integer_bytes("i32", rng.choice(ints["i32"]), rng)[:4]
                        + integer_bytes("i16", rng.choice(ints["i16"]), rng) for _ in range(600)]
    blocks["m64x8"] = [b"".join(rng.choice(f64).to_bytes(8, "little") for _ in range(8)) for _ in range(300)]
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, bytes(block).ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

def check(harness_path, native_path, lifted_path, *control_paths):
    expected = [(name, data, reference(name, data)) for name, data in cases()]
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            got, state = run(name, data)
            if not base.entry_state_ok(state):
                raise AssertionError(f"{label} {name} left state {state:#014x}; the profile requires control "
                                     "0x027f and an empty stack at TOP 0")
            if got != want:
                if bad < 3:
                    print(f"{label} mismatch: {name}(input {data[:24].hex()})\n  got      {got[:48].hex()}\n"
                          f"  expected {want[:48].hex()}")
                bad += 1
        if bad:
            raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    print(f"{len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the reference "
          "in native and translated DLLs; each export returned with control 0x027f and an empty stack")
    print(f"processor: {platform.processor()}")
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        failed = [name for name, (data, want) in first.items() if not base.preserved(run, "x87_call", name, data, want)]
        if failed:
            raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    print(f"x87_call kept a live caller ST(0) value and control word around all {len(first)} native and "
          "translated exports")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = base.Runner(harness_path, path)
        bad = sum(1 for name, data, want in expected if run(name, data)[0] != want)
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, {}, {}, x87=True)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "db 29", "db 3a"  # fld tbyte ptr [rcx]; fstp tbyte ptr [rdx]
    rejected = {
        "fbld m80": (attempt(f"{fld} df 21 {fstp} c3"), "unsupported x87 operation"),
        "fbstp m80": (attempt(f"{fld} df 31 {fstp} c3"), "unsupported x87 operation"),
        "fiadd m32 on an empty stack": (attempt(f"da 01 {fld} {fstp} c3"), "x87 stack underflow"),
        "fidivr m16 on an empty stack": (attempt(f"de 39 {fld} {fstp} c3"), "x87 stack underflow"),
        "fisub m32 with two values and one store": (attempt(f"{fld} {fld} da 21 {fstp} c3"),
                                                     "x87 stack not empty at return"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile: " + "; ".join(rejected))


if __name__ == "__main__":
    mode, first, second, *rest = sys.argv[1:]
    if mode == "asm":
        write_asm(first, second)
    elif mode == "emit":
        emit(Path(first), Path(second), *rest)
    elif mode == "check":
        check(first, second, *rest)
    else:
        raise ValueError(mode)
