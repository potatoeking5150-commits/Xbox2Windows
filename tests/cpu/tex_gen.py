"""Single source of truth for the EXE-entry textured-quad experiment.

The 8x8 RGBA8 texels are an original asymmetric rule (64/64 distinct
texels). The 8x8 BC7 texture reuses the repository's own mode-6 block
builder (tests/bc7_draw_check.make_block, 2x2 blocks) and its decoded
reference texels; the fixture also proves the 4 KiB standard-swizzle
tiled-to-linear conversion on the way in. The C++ provider embeds the
two 8x8 tables from the generated header and magnifies them to the
64x64 frame; shim_tex_check.py compares the same rules.
"""
import hashlib
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from bc7_draw_check import fixture  # noqa: E402

SIDE_TEX = 8
SIDE_RT = 64
SCALE = SIDE_RT // SIDE_TEX
SHIFT_TEXELS = 0.5  # texuv case shifts U by half a texel in the uploaded vertex buffer


def rgba8_texel(x, y):
    return ((x * 37 + 11) & 0xFF, (y * 53 + 29) & 0xFF, (((x ^ y) * 17 + 7) & 0xFF), 255)


def rgba8_table():
    return bytes(b for y in range(SIDE_TEX) for x in range(SIDE_TEX) for b in rgba8_texel(x, y))


def _bc7_case():
    _, linear, expected = fixture(columns=2, rows=2)
    return bytes(linear), bytes(expected)


def bc7_blocks():
    return _bc7_case()[0]


def bc7_table():
    return _bc7_case()[1]


def magnify(table):
    frame = bytearray()
    for y in range(SIDE_RT):
        row = table[(y // SCALE) * SIDE_TEX * 4:(y // SCALE + 1) * SIDE_TEX * 4]
        for x in range(SIDE_RT):
            frame += row[(x // SCALE) * 4:(x // SCALE + 1) * 4]
    return bytes(frame)


def shifted_frame(table):
    # Point sampling with U shifted by half a texel, magnified to the frame.
    frame = bytearray()
    for y in range(SIDE_RT):
        for x in range(SIDE_RT):
            u = (x + 0.5) / SIDE_RT + SHIFT_TEXELS / SIDE_TEX
            u = min(max(u, 0.0), 1.0 - 1e-9)
            tx = min(int(u * SIDE_TEX), SIDE_TEX - 1)
            ty = min(y // SCALE, SIDE_TEX - 1)
            frame += table[(ty * SIDE_TEX + tx) * 4:(ty * SIDE_TEX + tx + 1) * 4]
    return bytes(frame)


def tex_frame():
    return magnify(rgba8_table())


def texuv_frame():
    return shifted_frame(rgba8_table())


def bc7_frame():
    return magnify(bc7_table())


def corrupt_table(table):
    # Simulate a corrupted upload: flip every byte of texel (7, 7).
    raw = bytearray(table)
    base = (7 * SIDE_TEX + 7) * 4
    for i in range(4):
        raw[base + i] ^= 0xFF
    return bytes(raw)


def scene_frame():
    # Left half: RGBA8 table squeezed to 32x64; right half: BC7 table squeezed.
    rgba, bc7 = rgba8_table(), bc7_table()
    frame = bytearray()
    for y in range(SIDE_RT):
        for x in range(SIDE_RT):
            half = x if x < SIDE_RT // 2 else x - SIDE_RT // 2
            table = rgba if x < SIDE_RT // 2 else bc7
            tx, ty = half // 4, y // SCALE
            frame += table[(ty * SIDE_TEX + tx) * 4:(ty * SIDE_TEX + tx + 1) * 4]
    return bytes(frame)


def texbad_frame():
    return magnify(corrupt_table(rgba8_table()))


def write_bmp(path, side, rgba):
    row_size = (side * 3 + 3) & ~3
    pixels = bytearray()
    for y in range(side - 1, -1, -1):
        row = bytearray()
        for x in range(side):
            px = rgba[(y * side + x) * 4:(y * side + x + 1) * 4]
            row += bytes((px[2], px[1], px[0]))
        row += b"\x00" * (row_size - side * 3)
        pixels += row
    header = struct.pack("<2sIHHI", b"BM", 54 + len(pixels), 0, 0, 54)
    info = struct.pack("<IIIHHIIIIII", 40, side, side, 1, 24, 0, len(pixels), 0, 0, 0, 0)
    Path(path).write_bytes(header + info + bytes(pixels))


def emit_header(path):
    rgba, bc7 = rgba8_table(), bc7_table()
    lines = ["#pragma once", "// Generated by tests/cpu/tex_gen.py; do not edit.",
             "static const unsigned char tex_rgba8[256] = {"]
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in rgba) + "\n};")
    lines.append("static const unsigned char tex_bc7[256] = {")
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in bc7) + "\n};")
    lines.append("static const unsigned char tex_bc7_blocks[64] = {")
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in bc7_blocks()) + "\n};")
    Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    emit_header(Path(sys.argv[1]))
    print("rgba8 frame sha:", hashlib.sha256(tex_frame()).hexdigest()[:16])
    print("bc7 frame sha:", hashlib.sha256(bc7_frame()).hexdigest()[:16])
