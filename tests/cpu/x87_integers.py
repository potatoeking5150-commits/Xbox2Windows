"""Compare native and translated integer conversions of the x87 leaf-function profile: FILD with an
m16, m32 or m64 operand, FIST with m16 or m32, and FISTP and FISTTP with m16, m32 or m64.

Usage:
    python tests/cpu/x87_integers.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_integers.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_integers.py check <harness> <native> <lifted> [controls...]

The exports, harness and guards follow tests/cpu/x87_add.py, and the other steps use the format of
tests/cpu/x87_moves.py. emit checks that every decoded x87 instruction is the form its sequence names.
The model below converts with Fraction arithmetic and is independent of tools/x87_soft.h.
"""
from fractions import Fraction
from pathlib import Path
import platform
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import x87_add as base  # noqa: E402  (tests/cpu is the script directory)
import x87_moves as moves  # noqa: E402
from x87_add import J, classify, from_binary, m80_bytes, m80_exact, round_even, to_binary  # noqa: E402
from x87_div import SIZE as FLOAT_SIZE  # noqa: E402

INPUT, OUTPUT = base.INPUT, base.OUTPUT
BITS = {"i16": 16, "i32": 32, "i64": 64}
PTR = {"i16": "word", "i32": "dword", "i64": "qword"}
SIZE = {**FLOAT_SIZE, "i16": 2, "i32": 4, "i64": 8}
INTEGER_OPS = ("fild", "fist", "fistp", "fisttp")

# Integer steps are (op, "i16" | "i32" | "i64", offset); the others use the x87_moves format.
SEQUENCES = {
    **{f"fild_{k}": (k, [("fild", k, 0), ("fstp", "m80", 0)]) for k in BITS},
    "fild_i64_m64": ("i64", [("fild", "i64", 0), ("fstp", "m64", 0)]),
    "fild_i64_m32": ("i64", [("fild", "i64", 0), ("fstp", "m32", 0)]),
    "fild_i32_add": ("i32m80", [("fild", "i32", 0), ("fld", "m80", 16), ("faddp", "pop", 1), ("fstp", "m80", 0)]),
    **{f"fistp_{k}": ("m80", [("fld", "m80", 0), ("fistp", k, 0)]) for k in BITS},
    # FIST stores and keeps ST(0); the register goes out through FSTP m80 after it.
    **{f"fist_{k}": ("m80", [("fld", "m80", 0), ("fist", k, 0), ("fstp", "m80", 16)]) for k in ("i16", "i32")},
    **{f"fisttp_{k}": ("m80", [("fld", "m80", 0), ("fisttp", k, 0)]) for k in BITS},
    "fild_fistp_i64": ("i64", [("fild", "i64", 0), ("fistp", "i64", 0)]),
    "fild_fisttp_i16": ("i16", [("fild", "i16", 0), ("fisttp", "i16", 0)]),
    "fistp_two": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("fistp", "i32", 0), ("fistp", "i64", 8)]),
    "fild_depth8": ("m64x7i16", [("fld", "m64", 8 * k) for k in range(7)] + [("fild", "i16", 56)]
                    + [("fstp", "m64", 8 * k) for k in range(8)]),
}

CONTROLS = {
    # FIST and FISTP truncate like FISTTP.
    "chopall": (re.compile(r", (16|32|64), false, x87_cw\)"), r", \1, true, x87_cw)"),
    # FISTTP rounds to nearest like FIST.
    "roundtt": (re.compile(r", (16|32|64), true, x87_cw\)"), r", \1, false, x87_cw)"),
    # An out-of-range value saturates instead of giving the integer indefinite.
    "saturate": (re.compile(r"if \(magnitude > indefinite - \(x87_sign\(v\) \? 0 : 1\)\) return indefinite;"),
                 "if (magnitude > indefinite - (x87_sign(v) ? 0 : 1)) return x87_sign(v) ? indefinite : indefinite - 1;"),
    # A NaN converts to 0.
    "nanzero": (re.compile(r"if \(x87_unsupported\(v\) \|\| x87_exp\(v\) == 0x7fff\) return indefinite;"),
                "if (x87_is_nan(v)) return 0; if (x87_unsupported(v) || x87_exp(v) == 0x7fff) return indefinite;"),
    # FILD m16 and m32 zero-extend instead of sign-extending.
    "zext": (re.compile(r"static_cast<int(16|32)_t>\((load(?:_always)?)<uint\1_t>\(a\)\)"), r"static_cast<int64_t>(\2<uint\1_t>(a))"),
    # FILD keeps only 53 significand bits, as if the precision control applied to it.
    "fild53": (re.compile(r"return \{magnitude << shift, "), "return {(magnitude << shift) & ~0x7ffull, "),
}


# ---- MASM generation and decoding ------------------------------------------------------------------

def asm_line(step):
    op, *args = step
    if op in INTEGER_OPS:
        return f"    {op} {PTR[args[0]]} ptr [{'rcx' if op == 'fild' else 'rdx'}+{args[1]}]"
    return moves.asm_line(step)


def expected_form(step):
    return (step[0], step[1]) if step[0] in INTEGER_OPS else moves.expected_form(step)


def decoded_form(i):
    from iced_x86 import MemorySize as S, Mnemonic as M

    if i.mnemonic in (M.FILD, M.FIST, M.FISTP, M.FISTTP):
        name = next(n for n, v in vars(M).items() if v == i.mnemonic).lower()
        return name, {S.INT16: "i16", S.INT32: "i32", S.INT64: "i64"}[i.memory_size]
    return moves.decoded_form(i)


def write_asm(asm_path, def_path):
    lines = ["; coverage: source cpu_aot_x87_integers",
             "; Generated by tests/cpu/x87_integers.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for the integer conversions of the x87 leaf-function",
             "; profile. Each export reads an input block at RCX, writes an output block at RDX and returns",
             "; with the x87 stack empty.", ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER, is_x87

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name, (_, steps) in SEQUENCES.items():
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            body = region(pe, *bounds)
            decoded = [decoded_form(i) for i in body if is_x87(i)]
            wanted = [expected_form(s) for s in steps]
            if decoded != wanted:
                raise AssertionError(f"{name} assembled as {decoded}, expected {wanted}")
            code = lower(body, ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------

def from_integer(n):
    """FILD: the exact m80 encoding of the integer n; zero is +0."""
    return (0, 0) if n == 0 else m80_exact(int(n < 0), Fraction(abs(n)))


def to_integer(v, bits, chop):
    """FIST/FISTP (nearest-even) or FISTTP (chop): two's-complement bits, or the integer indefinite for a
    NaN, an infinity, an unsupported encoding or a rounded value outside the range."""
    indefinite = 1 << (bits - 1)
    c = classify(v)
    if c[0] in ("unsupported", "nan", "inf"):
        return indefinite
    if c[0] == "zero":
        return 0
    q = c[2]
    magnitude = q.numerator // q.denominator if chop else round_even(q)
    if magnitude > indefinite - (0 if c[1] else 1):
        return indefinite
    return (-magnitude if c[1] else magnitude) & ((1 << bits) - 1)


def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)

    def read(kind, offset):
        return int.from_bytes(data[offset:offset + SIZE[kind]], "little")

    for op, *args in SEQUENCES[name][1]:
        kind = args[0]
        if op == "fild":
            raw = read(*args)
            slots.append(from_integer(raw - (1 << BITS[kind]) if raw >> (BITS[kind] - 1) else raw))
        elif op in ("fist", "fistp", "fisttp"):
            bits = to_integer(slots[-1], BITS[kind], op == "fisttp")
            out[args[1]:args[1] + SIZE[kind]] = bits.to_bytes(SIZE[kind], "little")
            if op != "fist":
                slots.pop()
        elif op == "fld":
            raw = read(*args)
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if kind == "m80" else from_binary(kind, raw))
        elif op == "fstp":
            v = slots.pop()
            encoded = v[0] | v[1] << 64 if kind == "m80" else to_binary(kind, v)
            out[args[1]:args[1] + SIZE[kind]] = encoded.to_bytes(SIZE[kind], "little")
        else:  # ("faddp", "pop", 1)
            slots[-2] = base.add(slots[-2], slots[-1])
            slots.pop()
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def integers(bits, rng):
    top = 1 << (bits - 1)
    values = {0, 1, -1, 2, -2, 3, top - 1, -top, top - 2, -top + 1, 1 << (bits // 2), -(1 << (bits // 2))}
    if bits == 64:  # around the binary64 and binary32 significand widths
        values |= {(1 << 53) + 1, -(1 << 53) - 1, (1 << 53) + 3, (1 << 54) + 2, (1 << 24) + 1, (1 << 62) + (1 << 9)}
    values |= {rng.randrange(-top, top) for _ in range(60)}
    values |= {rng.choice((1, -1)) * rng.getrandbits(rng.randint(1, bits - 1)) for _ in range(60)}
    return sorted(values)


def exact_m80(q):
    """The m80 encoding of a nonzero Fraction q, or None when it needs more than 64 significand bits."""
    try:
        return m80_exact(int(q < 0), abs(q))
    except AssertionError:
        return None


def float_inputs(rng):
    values = list(base.m80_singles())
    half, quarter = Fraction(1, 2), Fraction(1, 4)
    centers = [Fraction(k) for k in range(-6, 7)]
    for bits in (16, 32, 64):
        top = 1 << (bits - 1)
        centers += [Fraction(c) for c in (top - 1, top, -top, -top - 1, top - 2, -top + 1, top // 3, -(top // 3))]
    for c in centers:
        for d in (0, half, -half, quarter, -quarter, 3 * quarter, -3 * quarter, Fraction(1, 1 << 40),
                  -Fraction(1, 1 << 40), half + Fraction(1, 1 << 40), half - Fraction(1, 1 << 40)):
            v = exact_m80(c + d) if c + d else (0, 0)
            if v is not None:
                values.append(v)
    for _ in range(400):  # random magnitudes from 2^-3 up to just below 2^67
        values.append((J | rng.getrandbits(63), rng.randint(0x3FFF - 3, 0x3FFF + 66) | rng.choice((0, 0x8000))))
    return values


def cases():
    rng = random.Random(29)
    ints = {k: integers(b, rng) for k, b in BITS.items()}
    floats = float_inputs(rng)
    f64 = base.f64_bits()

    def int_bytes(k, n):
        return (n & ((1 << BITS[k]) - 1)).to_bytes(SIZE[k], "little")

    blocks = {
        **{k: [int_bytes(k, n) for n in ints[k]] for k in BITS},
        "i32m80": [int_bytes("i32", n).ljust(16, b"\0") + m80_bytes(v)
                   for n in ints["i32"][::4] for v in floats[::40]],
        "m80": [m80_bytes(v) for v in floats],
        "pair80": [m80_bytes(a) + m80_bytes(b) for a, b in zip(floats, reversed(floats))],
        "m64x7i16": [b"".join(rng.choice(f64).to_bytes(8, "little") for _ in range(7))
                     + int_bytes("i16", rng.choice(ints["i16"])) for _ in range(300)],
    }
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, block.ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

def check(harness_path, native_path, lifted_path, *control_paths):
    expected = [(name, data, reference(name, data)) for name, data in cases()]
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            got, state = run(name, data)
            if not base.entry_state_ok(state):
                raise AssertionError(f"{label} {name} left state {state:#014x}; the profile requires control "
                                     "0x027f and an empty stack at TOP 0")
            if got != want:
                if not bad:
                    print(f"{label} first mismatch: {name}(input {data[:48].hex()})\n  got      {got[:48].hex()}\n"
                          f"  expected {want[:48].hex()}")
                bad += 1
        if bad:
            raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    print(f"{len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the reference "
          "in native and translated DLLs; each export returned with control 0x027f and an empty stack")
    print(f"processor: {platform.processor()}")
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        failed = [name for name, (data, want) in first.items() if not base.preserved(run, "x87_call", name, data, want)]
        if failed:
            raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    print(f"x87_call kept a live caller ST(0) value and control word around all {len(first)} native and "
          "translated exports")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = base.Runner(harness_path, path)
        bad = sum(1 for name, data, want in expected if run(name, data)[0] != want)
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, {}, {}, x87=True)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "db 29", "db 3a"  # fld tbyte ptr [rcx]; fstp tbyte ptr [rdx]
    rejected = {
        "fild m16 at depth 8": (attempt(f"{fld} " * 8 + "df 01 " + f"{fstp} " * 9 + "c3"), "x87 stack overflow"),
        "fistp m32 on an empty stack": (attempt("db 1a c3"), "x87 stack underflow"),
        "fist m16 on an empty stack": (attempt("df 12 c3"), "x87 stack underflow"),
        "fisttp m64 on an empty stack": (attempt("dd 0a c3"), "x87 stack underflow"),
        "fist m32 without a pop": (attempt(f"{fld} db 12 c3"), "x87 stack not empty at return"),
        "fldenv": (attempt(f"{fld} d9 21 {fstp} c3"), "unsupported x87 operation"),
        "fyl2xp1": (attempt(f"{fld} d9 f9 {fstp} c3"), "unsupported x87 operation"),
        "fbld m80": (attempt(f"df 21 {fstp} c3"), "unsupported x87 operation"),
        "fbstp m80": (attempt(f"{fld} df 32 c3"), "unsupported x87 operation"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile: " + "; ".join(rejected))


if __name__ == "__main__":
    mode, first, second, *rest = sys.argv[1:]
    if mode == "asm":
        write_asm(first, second)
    elif mode == "emit":
        emit(Path(first), Path(second), *rest)
    elif mode == "check":
        check(first, second, *rest)
    else:
        raise ValueError(mode)
